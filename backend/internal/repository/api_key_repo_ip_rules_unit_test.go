//go:build unit

package repository

import (
	"context"
	"fmt"
	"strings"
	"testing"

	"github.com/DATA-DOG/go-sqlmock"
	dbent "github.com/Wei-Shaw/sub2api/ent"
	"github.com/Wei-Shaw/sub2api/internal/service"
	"github.com/stretchr/testify/require"

	"entgo.io/ent/dialect"
	entsql "entgo.io/ent/dialect/sql"
)

func TestAPIKeyRepositoryIPRulesPostgresSQL(t *testing.T) {
	for _, tt := range []struct {
		name   string
		fields service.APIKeyUpdateFields
		clear  bool
	}{
		{"whitelist", service.APIKeyUpdateFields{IPWhitelist: true}, false},
		{"blacklist", service.APIKeyUpdateFields{IPBlacklist: true}, false},
		{"clear whitelist", service.APIKeyUpdateFields{IPWhitelist: true}, true},
		{"clear blacklist", service.APIKeyUpdateFields{IPBlacklist: true}, true},
		{"both explicitly", service.APIKeyUpdateFields{IPWhitelist: true, IPBlacklist: true}, false},
		{"legacy both", service.APIKeyUpdateFields{IPRules: true}, false},
		{"legacy clear both", service.APIKeyUpdateFields{IPRules: true}, true},
	} {
		t.Run(tt.name, func(t *testing.T) {
			// Inspect SQL generated by the real PostgreSQL Ent adapter, including
			// absence of the unrequested column; allow harmless SET ordering changes.
			matcher := sqlmock.QueryMatcherFunc(func(_, actual string) error {
				set, where, ok := strings.Cut(actual, " WHERE ")
				if !ok || !strings.HasPrefix(set, `UPDATE "api_keys" SET `) || !strings.Contains(where, `"id"`) || !strings.Contains(where, `"deleted_at" IS NULL`) {
					return fmt.Errorf("unexpected ACL update SQL: %s", actual)
				}
				for column, wanted := range map[string]bool{
					"ip_whitelist": tt.fields.IPWhitelist || tt.fields.IPRules,
					"ip_blacklist": tt.fields.IPBlacklist || tt.fields.IPRules,
				} {
					if strings.Contains(set, `"`+column+`"`) != wanted {
						return fmt.Errorf("unexpected persistence of %s in %s", column, actual)
					}
					if wanted && tt.clear && !strings.Contains(set, `"`+column+`" = NULL`) {
						return fmt.Errorf("explicit clear missing for %s: %s", column, actual)
					}
				}
				return nil
			})
			db, mock, err := sqlmock.New(sqlmock.QueryMatcherOption(matcher))
			require.NoError(t, err)
			client := dbent.NewClient(dbent.Driver(entsql.OpenDB(dialect.Postgres, db)))
			t.Cleanup(func() { _ = client.Close() })
			key := &service.APIKey{ID: 11, IPWhitelist: []string{"203.0.113.0/24"}, IPBlacklist: []string{"203.0.113.8"}}
			if tt.clear {
				key.IPWhitelist, key.IPBlacklist = nil, nil
			}
			mock.ExpectExec("ACL update").WillReturnResult(sqlmock.NewResult(0, 1))
			require.NoError(t, newAPIKeyRepositoryWithSQL(client, db).Update(context.Background(), key, tt.fields))
			require.NoError(t, mock.ExpectationsWereMet())
		})
	}
}
